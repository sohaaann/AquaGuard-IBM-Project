"""Dev-time tool (NOT needed to use the app): generates the SYNTHETIC demo dataset and js/data.js.

Outputs
  data/demo-water-quality.csv   (120 fictional records, 4 fictional sites, fixed seed)
  js/data.js                    (demo rows + reference profiles + settings as plain JS, so index.html works from file://)
The JSON in config/ is the source of truth for thresholds; this script embeds it.
"""
import csv, json, random
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
random.seed(20261010)
COLS = ["sample_id", "sample_date", "location", "source_type", "ph", "turbidity_ntu", "tds_mg_l",
        "temperature_c", "conductivity_us_cm", "dissolved_oxygen_mg_l"]
# fictional sites: name, source, ph, turbidity, tds, temp, conductivity factor, DO mean (None = not measured)
SITES = [("Site A", "tap", 7.4, 0.5, 260, 26.0, 1.55, None),
         ("Site B", "borewell", 7.8, 0.4, 470, 27.0, 1.65, None),
         ("Site C", "tank", 7.6, 0.6, 380, 26.5, 1.60, 7.1),
         ("Site D", "river", 7.0, 0.8, 220, 25.0, 1.50, 6.3)]
rows = []
for si, (site, src, ph, tb, tds, tmp, ecf, do) in enumerate(SITES):
    d = date(2026, 8, 1) + timedelta(days=si)
    for k in range(30):
        drift = k / 29
        v_ph = random.gauss(ph, 0.22)
        v_tb = abs(random.gauss(tb + (0.5 * drift if site == "Site C" else 0), 0.18 if tb < 0.75 else 0.35))
        v_tds = max(40, random.gauss(tds + (70 * drift if site == "Site B" else 0), 28))
        v_tmp = random.gauss(tmp - 1.5 * drift, 0.8)
        rec = dict(sample_id="", sample_date=d.isoformat(), location=site, source_type=src,
                   ph=round(v_ph, 2), turbidity_ntu=round(v_tb, 2), tds_mg_l=round(v_tds),
                   temperature_c=round(v_tmp, 1),
                   conductivity_us_cm=None if random.random() < 0.18 else round(v_tds * ecf),
                   dissolved_oxygen_mg_l=None if do is None or random.random() < 0.10 else round(random.gauss(do, 0.4), 2))
        rows.append(rec)
        d += timedelta(days=(2, 2, 3)[k % 3])
# synthetic spikes / unusual observations / missing measurements (positions chosen once, deterministic)
rows[12].update(ph=9.4)                                    # pH excursion
rows[37].update(turbidity_ntu=18.5)                        # turbidity spike
rows[58].update(tds_mg_l=1480, conductivity_us_cm=2350)    # TDS spike
rows[81].update(temperature_c=36.5)                        # warm sample
rows[96].update(ph=5.3, turbidity_ntu=7.9)                 # acidic + turbid
for i in (20, 45, 70, 101):                                # only pH and temperature measured -> insufficient data
    rows[i].update(turbidity_ntu=None, tds_mg_l=None, conductivity_us_cm=None)
for i in (30, 77):
    rows[i].update(ph=None)
rows.sort(key=lambda r: (r["sample_date"], r["location"]))
for i, r in enumerate(rows, 1):
    r["sample_id"] = f"DEMO-{i:03d}"
with open(ROOT / "data" / "demo-water-quality.csv", "w", newline="", encoding="utf-8") as fh:
    w = csv.writer(fh, lineterminator="\n"); w.writerow(COLS)
    for r in rows:
        w.writerow(["" if r[c] is None else r[c] for c in COLS])
refs = json.loads((ROOT / "config" / "water-quality-references.json").read_text(encoding="utf-8"))
settings = {"appName": "AquaGuard AI", "defaultProfile": "BIS_IS10500_acceptable", "minParametersForScreening": 2,
            "outlierZ": 3.5, "outlierMinSamples": 8, "futureToleranceDays": 1, "demoVersion": "2026-10-10"}
js = ("/* GENERATED by scripts/build_data.py - do not edit by hand. SYNTHETIC demo data + reference config. */\n"
      "window.AQ = window.AQ || {};\n"
      f"AQ.DEMO_COLUMNS = {json.dumps(COLS)};\n"
      f"AQ.DEMO_ROWS = {json.dumps(rows, separators=(',', ':'))};\n"
      f"AQ.REFERENCES = {json.dumps(refs, indent=1)};\n"
      f"AQ.SETTINGS = {json.dumps(settings)};\n")
(ROOT / "js" / "data.js").write_text(js, encoding="utf-8")
print("rows:", len(rows), "| csv + js/data.js written")
